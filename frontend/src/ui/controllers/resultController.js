/**
 * Menyusun langkah rute sintetis minimal jika payload rute dari cache lama belum memuat steps[].
 */
function susunLangkahFallback(route, asal, tujuan) {
  const geom = Array.isArray(route?.geometry) ? route.geometry : [];
  const startCoord = geom[0] || (asal ? [asal.lon, asal.lat] : null);
  const midCoord = geom[Math.floor(geom.length / 2)] || startCoord;
  const endCoord = geom[geom.length - 1] || (tujuan ? [tujuan.lon, tujuan.lat] : null);
  const koridor = route?.summary || 'Main Corridor';
  const distM = Number(route?.distanceM) || 0;
  const durS = Number(route?.durationS) || 0;

  return [
    {
      index: 1,
      instruction: `Start trip from ${asal?.nama || 'Origin'}`,
      roadName: koridor,
      directionKey: 'depart',
      distanceM: Math.round(distM * 0.2),
      durationS: Math.round(durS * 0.2),
      location: startCoord,
    },
    {
      index: 2,
      instruction: `Follow ${koridor}`,
      roadName: koridor,
      directionKey: 'straight',
      distanceM: Math.max(0, distM - Math.round(distM * 0.2)),
      durationS: Math.max(0, durS - Math.round(durS * 0.2)),
      location: midCoord,
    },
    {
      index: 3,
      instruction: `Arrive at ${tujuan?.nama || 'Destination'}`,
      roadName: tujuan?.nama || 'Destination',
      directionKey: 'arrive',
      distanceM: 0,
      durationS: 0,
      location: endCoord,
    },
  ];
}

/** Menyimpan daftar langkah aktif saat ini untuk interaksi klik fokus peta */
let langkahAktifSekarang = [];

/**
 * Menggambar daftar langkah manuver rute (Turn-by-Turn Steps) di sidebar hasil.
 * @param {object} route
 * @param {object|null} asal
 * @param {object|null} tujuan
 */
function gambarLangkahRute(route, asal = null, tujuan = null) {
  const wadah = $('#stepsList');
  const lencanaJumlah = $('#stepsCountBadge');
  if (!wadah) return;

  const steps = Array.isArray(route?.steps) && route.steps.length > 0
    ? route.steps
    : susunLangkahFallback(route, asal, tujuan);

  langkahAktifSekarang = steps;

  if (lencanaJumlah) {
    lencanaJumlah.textContent = `${steps.length} steps`;
  }

  wadah.innerHTML = steps.map((step, idx) => {
    const dirKey = step.directionKey || 'straight';
    const isTerminal = dirKey === 'depart' || dirKey === 'arrive';
    const jarakTeks = step.distanceM > 0 ? formatJarak(step.distanceM) : (dirKey === 'arrive' ? 'Arrive' : '0 m');
    const durTeks = step.durationS > 0 ? formatDurasi(step.durationS) : '';
    const namaJalan = step.roadName || '';
    const adaKoordinat = Array.isArray(step.location) && step.location.length >= 2;

    return `
      <li class="stepitem" data-step-index="${idx}" data-dir="${pelarian(dirKey)}" ${adaKoordinat ? 'tabindex="0" role="button" title="Click to focus this step on the map"' : ''}>
        <div class="stepitem__rail" aria-hidden="true">
          <span class="stepitem__icon stepitem__icon--${pelarian(dirKey)}">
            ${ikonUntukArahLangkah(dirKey)}
          </span>
          ${idx < steps.length - 1 ? '<span class="stepitem__line"></span>' : ''}
        </div>
        <div class="stepitem__body">
          <div class="stepitem__top">
            <span class="stepitem__instruction">${pelarian(step.instruction || 'Continue along route')}</span>
            <span class="stepitem__dist">${pelarian(jarakTeks)}</span>
          </div>
          <div class="stepitem__meta">
            <span class="stepitem__num">Step ${step.index || idx + 1}</span>
            ${namaJalan && !isTerminal ? `<span class="stepitem__sep">·</span><span class="stepitem__road">${pelarian(namaJalan)}</span>` : ''}
            ${durTeks ? `<span class="stepitem__sep">·</span><span class="stepitem__dur">${pelarian(durTeks)}</span>` : ''}
          </div>
        </div>
      </li>`;
  }).join('');
}

/**
 * Memilih salah satu rute kandidat berdasarkan indeks (0, 1, 2...),
 * memperbarui kartu skor/detail di sidebar serta menyorot rute terpilih di peta 3D.
 *
 * @param {number} index
 */
export function pilihRuteByIndex(index) {
  const keadaan = getState();
  const hasilSekarang = keadaan.hasil;
  if (!hasilSekarang) return;

  const semuaPilihan = susunDaftarPilihanRute(hasilSekarang);
  const target = semuaPilihan[index];
  if (!target) return;

  const hasilBaru = {
    ...hasilSekarang,
    semuaPilihan,
    indeksRuteAktif: index,
    hanyaGantiPilihan: true,
    route: target.route,
    score: target.score,
    air: target.air,
    visual: target.visual,
  };

  gambarHasil(hasilBaru);
  setState({ hasil: hasilBaru });
}

/** Memeriksa dan menampilkan peringatan area rawan banjir/genangan + catatan tol motor di sepanjang rute. */
async function renderPeringatanRute(aktifOpt, hasil) {
  const banner = $('#routeHazardAlert');
  const listEl = $('#routeHazardList');
  const titleEl = $('#routeHazardTitle');
  if (!banner || !listEl) return;

  pengendaliCekRuteRawan?.abort();
  pengendaliCekRuteRawan = new AbortController();

  const profil = hasil?.profil || getState().profil || 'car';
  const motorTollNotice = profil === 'motor' && Boolean(aktifOpt?.route?.usesToll);
  const { pengguna } = getState();
  const alertPref = pengguna?.alertPreferences || { enabled: true, minSeverity: 'waspada' };
  const autoEnabled = alertPref.enabled !== false;

  const renderBanner = (alerts = []) => {
    hasilRuteRawanTersimpan = alerts;
    if (!alerts.length && !motorTollNotice) {
      banner.hidden = true;
      listEl.innerHTML = '';
      return;
    }

    const hasSiaga = alerts.some((a) => a.severity === 'siaga');
    banner.dataset.sev = hasSiaga ? 'siaga' : 'waspada';
    if (titleEl) {
      titleEl.textContent = alerts.length > 0
        ? `${alerts.length} Hazard ${alerts.length === 1 ? 'Area' : 'Areas'} Near Route`
        : 'Motorcycle Route Note';
    }

    const itemsHtml = alerts.map((a, idx) => `
      <li class="hazardbanner__item">
        <span class="hazardbanner__text">
          <strong>[${escapeHtml(a.severityLabel || 'Caution')}] ${escapeHtml(a.corridor)}</strong>
          · ${escapeHtml(a.summary)}
        </span>
        <button type="button" class="hazardbanner__btn press" data-focus-hazard="${idx}">View on Map</button>
      </li>`).join('');

    const tollHtml = motorTollNotice
      ? `<li class="hazardbanner__item">
           <span class="hazardbanner__text">
             <strong>[Motorbike Info] Toll Segment Detected</strong>
             · The routing engine only returned a toll-road path for this corridor; pick an arterial alternative if available.
           </span>
         </li>`
      : '';

    listEl.innerHTML = `${tollHtml}${itemsHtml}`;
    banner.hidden = false;
  };

  if (!autoEnabled || !Array.isArray(aktifOpt?.route?.geometry) || aktifOpt.route.geometry.length === 0) {
    renderBanner([]);
    return;
  }

  renderBanner([]);
  try {
    const res = await cekPeringatanRute({
      geometry: aktifOpt.route.geometry,
      radiusM: 900,
      minSeverity: alertPref.minSeverity || 'waspada',
      signal: pengendaliCekRuteRawan.signal,
    });
    if (Array.isArray(res?.alerts)) {
      renderBanner(res.alerts);
    }
  } catch (err) {
    if (err?.name !== 'AbortError') {
      console.warn('[alerts] Pemeriksaan rute rawan dilewati:', err?.message);
    }
  }
}

/**
 * Menggambar seluruh layar hasil dari satu objek hasil navigasi.
 * @param {object} hasil
 */
export function gambarHasil(hasil) {
  const semuaPilihan = susunDaftarPilihanRute(hasil);
  const indeksAktif = Number.isInteger(hasil.indeksRuteAktif) ? hasil.indeksRuteAktif : 0;
  const aktifOpt = semuaPilihan[indeksAktif] || semuaPilihan[0];

  hasil.semuaPilihan = semuaPilihan;
  hasil.indeksRuteAktif = indeksAktif;

  gambarSumber(hasil.sumber);

  const namaAsal = hasil.asal?.nama || 'Origin';
  const namaTujuan = hasil.tujuan?.nama || 'Destination';
  setText($('#sRouteFrom'), namaAsal);
  setText($('#sRouteTo'), namaTujuan);

  // Header Petunjuk Arah (dirhead)
  setText($('#sDirOriginName'), namaAsal);
  setText($('#sDirOriginArea'), hasil.asal?.area || '');
  setText($('#sDirDestName'), namaTujuan);
  setText($('#sDirDestArea'), hasil.tujuan?.area || '');

  const infoProfil = PROFILES.find((p) => p.key === (hasil.profil || getState().profil));
  setText($('#sProfileBadge'), infoProfil ? infoProfil.nama : 'Car');

  // Gambar daftar pemilih rute interaktif (1, 2, 3...)
  gambarPilihanRute(semuaPilihan, indeksAktif);

  // Kartu metrik & skor mengikuti rute yang sedang dipilih
  const effMin = aktifOpt.score?.breakdown?.time?.effectiveDurationMin;
  const durDetikEfektif = Number.isFinite(effMin) ? effMin * 60 : aktifOpt.route?.durationS;
  setText($('#sDistance'), formatJarak(aktifOpt.route?.distanceM));
  setText($('#sDuration'), formatDurasi(durDetikEfektif));

  gambarSkor(aktifOpt.score);

  const elReason = $('#sReason');
  if (elReason) {
    if (indeksAktif === 0 && hasil.reason) {
      elReason.innerHTML = renderMarkdownAman(hasil.reason);
    } else if (indeksAktif > 0) {
      const koridor = aktifOpt.route?.summary || `Jalur Alternatif ${indeksAktif + 1}`;
      const ringkasanAlt = `**Rute ${indeksAktif + 1} (${koridor})** memiliki skor risiko gabungan **${aktifOpt.score.totalScore}/100 (${aktifOpt.score.label})**. ${susunAlasan(aktifOpt.score)}`;
      elReason.innerHTML = renderMarkdownAman(ringkasanAlt);
    } else {
      setText(elReason, susunAlasan(aktifOpt.score));
    }
  }

  gambarRincian(aktifOpt.score);
  gambarLangkahRute(aktifOpt.route, hasil.asal, hasil.tujuan);
  gambarUdara(aktifOpt.air, aktifOpt.score);
  gambarKamera(aktifOpt.visual);
  renderPeringatanRute(aktifOpt, hasil);

  // Tombol simpan dikembalikan ke keadaan awal tiap hasil baru.
  setText($('#saveLabel'), 'Save route');
  $('#btnSaveRoute')?.removeAttribute('data-tersimpan');
}

/**
 * Memasang perilaku tombol di layar hasil. Dipanggil sekali dari main.js.
 */
export function pasangPengendaliHasil() {
  // Klik pada salah satu kartu rute di daftar Pilihan Rute (#routeOptionsList)
  $('#routeOptionsList')?.addEventListener('click', (e) => {
    const item = e.target.closest('[data-route-index]');
    if (!item) return;
    const idx = Number(item.dataset.routeIndex);
    if (Number.isInteger(idx)) {
      pilihRuteByIndex(idx);
    }
  });

  // Klik "Lihat di Peta" pada banner peringatan area rawan di rute
  $('#routeHazardList')?.addEventListener('click', (e) => {
    const btn = e.target.closest('[data-focus-hazard]');
    if (!btn) return;
    const item = hasilRuteRawanTersimpan[Number(btn.dataset.focusHazard)];
    if (!item || !Number.isFinite(Number(item.lat)) || !Number.isFinite(Number(item.lon))) return;
    window.dispatchEvent(new CustomEvent('jaksafe:mobile-half'));
    flyToCoordinates({ lon: Number(item.lon), lat: Number(item.lat), height: 950 });
    toast(`Focused map on ${item.corridor}`);
  });

  $('#btnViewAllAlerts')?.addEventListener('click', () => {
    document.dispatchEvent(new CustomEvent('jaksafe:open-alerts'));
  });

  // Klik pada salah satu baris manuver di Panduan Langkah Rute (#stepsList)
  $('#stepsList')?.addEventListener('click', (e) => {
    const item = e.target.closest('[data-step-index]');
    if (!item) return;
    const idx = Number(item.dataset.stepIndex);
    const step = langkahAktifSekarang[idx];
    if (!step) return;

    $('#stepsList')?.querySelectorAll('.stepitem').forEach((el) => {
      el.dataset.active = el === item ? '1' : '0';
    });
    window.dispatchEvent(new CustomEvent('jaksafe:mobile-half'));
    focusStepOnMap(step);
  });

  // Tombol ciutkan / bentangkan daftar langkah manuver rute (#btnToggleSteps)
  const tombolSteps = $('#btnToggleSteps');
  tombolSteps?.addEventListener('click', () => {
    const terbuka = tombolSteps.getAttribute('aria-expanded') === 'true';
    tombolSteps.setAttribute('aria-expanded', String(!terbuka));
    show($('#stepsListWrap'), !terbuka);
  });

  // Tombol kembali / ubah titik awal atau tujuan di header Petunjuk Arah
  $('#btnBackSearch')?.addEventListener('click', () => {
    setState({ tampilan: 'siap' });
  });

  $('#btnEditOrigin')?.addEventListener('click', () => {
    setState({ tampilan: 'siap' });
    setTimeout(() => $('#inpOrigin')?.focus(), 60);
  });

  $('#btnEditDest')?.addEventListener('click', () => {
    setState({ tampilan: 'siap' });
    setTimeout(() => $('#inpDest')?.focus(), 60);
  });

  // Tombol tukar arah (swap) langsung dari layar hasil
  $('#btnResultSwap')?.addEventListener('click', () => {
    $('#btnSwap')?.click();
    $('#btnSearch')?.click();
  });

  $('#btnSaveRoute')?.addEventListener('click', async () => {
    const { masuk, token, hasil, ruteTersimpan } = getState();

    if (!masuk) {
      toast('Sign in or create an account first to save routes.');
      $('#loginModal') && show($('#loginModal'), true);
      return;
    }
    if (!hasil) return;

    const tombol = $('#btnSaveRoute');
    if (tombol?.dataset.tersimpan === '1') {
      toast('This route is already saved.');
      return;
    }

    const payload = {
      title: `${hasil.asal?.nama || 'Origin'} -> ${hasil.tujuan?.nama || 'Destination'}`,
      origin: {
        id: hasil.asal?.id || null,
        name: hasil.asal?.nama || 'Origin',
        area: hasil.asal?.area || '',
        lat: Number(hasil.asal?.lat) || 0,
        lon: Number(hasil.asal?.lon) || 0,
      },
      destination: {
        id: hasil.tujuan?.id || null,
        name: hasil.tujuan?.nama || 'Destination',
        area: hasil.tujuan?.area || '',
        lat: Number(hasil.tujuan?.lat) || 0,
        lon: Number(hasil.tujuan?.lon) || 0,
      },
      score: {
        totalScore: hasil.score.totalScore,
        label: hasil.score.label,
        color: hasil.score.color,
      },
      distanceM: hasil.route?.distanceM ?? hasil.distanceM ?? 0,
      durationS: hasil.route?.durationS ?? hasil.durationS ?? 0,
      profile: hasil.profil || hasil.profile || getState().profil || 'car',
    };

    if (tombol) tombol.style.opacity = '0.6';

    try {
      let savedObj = payload;
      if (token) {
        const res = await simpanRute(token, payload);
        if (res.route) savedObj = res.route;
      }

      setState({
        ruteTersimpan: [savedObj, ...ruteTersimpan],
      });

      if (tombol) {
        tombol.dataset.tersimpan = '1';
        tombol.style.opacity = '1';
      }
      setText($('#saveLabel'), 'Saved');
      toast('Route saved permanently!');
    } catch (err) {
      console.error('[saveRoute]', err);
      if (tombol) tombol.style.opacity = '1';
      toast('Failed to save route.');
    }
  });
}
